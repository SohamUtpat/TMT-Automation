export function uniqueFormBuilderData(suffix = "") {
  const unique = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}${suffix ? `-${suffix}` : ""}`;
  return {
    formName: `${FormsData.builder.uniqueData.formNamePrefix}-${unique}`,
    description: `${FormsData.builder.uniqueData.descriptionPrefix} ${unique}`,
    fieldLabel: `${FormsData.builder.uniqueData.fieldLabelPrefix} ${unique}`,
    optionLabel: `${FormsData.builder.uniqueData.optionLabelPrefix} ${unique}`,
    optionValue: `${FormsData.builder.uniqueData.optionValuePrefix}-${unique}`,
  };
}
